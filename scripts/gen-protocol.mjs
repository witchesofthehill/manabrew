#!/usr/bin/env node
// Regenerates the TypeScript wire-protocol types from `forge-protocol` (the
// single Rust source of truth) into `src/protocol/`, which is fully generated
// and gitignored. ts-rs emits the per-type files; this script then writes the
// barrels and the PromptOutput/PromptType unions (which ts-rs cannot express).
// The only hand-written protocol file is `src/protocolEnvelope.ts`.
import { execSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync, rmSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const protocolDir = join(repoRoot, "src", "protocol");
const promptsDir = join(protocolDir, "prompts");
const GENERATED_MARK = "generated by";
const HEADER =
  "// AUTO-GENERATED by scripts/gen-protocol.mjs — do not edit. Run `yarn gen:protocol`.\n";

function pruneGenerated(dir) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) pruneGenerated(p);
    else if (
      entry.endsWith(".ts") &&
      readFileSync(p, "utf8").toLowerCase().includes(GENERATED_MARK)
    )
      rmSync(p);
  }
}

pruneGenerated(protocolDir);

execSync("cargo test -p forge-protocol export_bindings -- --test-threads=1", {
  cwd: repoRoot,
  stdio: "inherit",
  env: { ...process.env, TS_RS_EXPORT_DIR: protocolDir },
});

const promptModules = readdirSync(promptsDir)
  .filter(
    (f) => f.endsWith(".ts") && f !== "index.ts" && f !== "promptInput.ts" && f !== "common.ts",
  )
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const outputs = [];
for (const m of promptModules) {
  const src = readFileSync(join(promptsDir, `${m}.ts`), "utf8");
  for (const match of src.matchAll(/export type (\w+Output)\b/g)) outputs.push(match[1]);
}

const promptsIndex =
  HEADER +
  `export * from "./common";\n` +
  `export * from "./promptInput";\n` +
  promptModules.map((m) => `export * from "./${m}";`).join("\n") +
  `\n\nimport type { PromptInput } from "./promptInput";\n` +
  outputs.map((o) => `import type { ${o} } from "./${moduleOf(o, promptModules)}";`).join("\n") +
  `\n\nexport type PromptType = PromptInput["type"];\n\n` +
  `export type PromptOutput =\n  | ${outputs.join("\n  | ")};\n`;
writeFileSync(join(promptsDir, "index.ts"), promptsIndex);

writeFileSync(join(protocolDir, "transport", "index.ts"), HEADER + `export * from "./messages";\n`);

writeFileSync(
  join(protocolDir, "index.ts"),
  HEADER +
    `export * from "./prompts";\n` +
    `export * from "./transport";\n` +
    `export type * from "./display";\n` +
    `export * from "@/protocolEnvelope";\n`,
);

function moduleOf(outputType, modules) {
  const found = modules.find((m) =>
    readFileSync(join(promptsDir, `${m}.ts`), "utf8").includes(`export type ${outputType} `),
  );
  return found ?? modules[0];
}

execSync("npx prettier --write src/protocol", { cwd: repoRoot, stdio: "inherit" });
console.log(`\nProtocol TypeScript regenerated into ${protocolDir}`);
